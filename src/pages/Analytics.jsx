import { useMemo } from 'react'
import { Bar, BarChart, CartesianGrid, Legend, Line, LineChart, ResponsiveContainer, Tooltip, XAxis, YAxis, ComposedChart, Area } from 'recharts'
import { DashboardShell, RequireRole } from '../components/Layouts.jsx'
import { Notice, Stat } from '../components/ui.jsx'
import { useStore } from '../lib/store.jsx'
import { computeAnalytics } from '../lib/analytics.js'
import { fmtMoney } from '../lib/util.js'

const C = { green: '#168a40', blue: '#2563eb', orange: '#ea580c', violet: '#7c3aed', slate: '#94a3b8' }

function Chart({ title, note, children, height = 260 }) {
  return (
    <div className="card p-4">
      <h3 className="font-bold">{title}</h3>
      {note && <p className="mb-2 text-xs text-slate-500">{note}</p>}
      <div style={{ height }}>
        <ResponsiveContainer width="100%" height="100%">{children}</ResponsiveContainer>
      </div>
    </div>
  )
}

export default function Analytics() {
  return (
    <RequireRole role="admin">
      <AnalyticsInner />
    </RequireRole>
  )
}

function AnalyticsInner() {
  const { state } = useStore()
  const a = useMemo(() => computeAnalytics(state, Date.now()), [state.orders, state.queue, state.sessions, state.orderItems])
  const k = a.kpis
  const grid = { stroke: '#e2e8f0', strokeDasharray: '3 3' }
  return (
    <DashboardShell area="admin" title="Analytics">
      <div className="space-y-5">
        <Notice tone="warn">
          <b>Demonstration data.</b> The last 10 days are synthetic, generated by a fixed random seed, plus whatever you do in this demo session. These numbers illustrate what the dashboard measures. They are <b>not</b> real restaurant results and do not prove any improvement.
        </Notice>

        <div className="grid grid-cols-2 gap-3 lg:grid-cols-5">
          <Stat label="Avg waiting time" value={`${k.avgWait} min`} sub="join → seated (queued guests)" />
          <Stat label="Seated → first dish" value={`${k.seatToFirstServed} min`} sub="clock starts at seating / order" />
          <Stat label="Avg dish prep time" value={`${k.avgPrep} min`} sub="actual, from kitchen taps" />
          <Stat label="Table turnover" value={`${k.turnover}×`} sub={`parties per table per day · avg stay ${k.dwell} min`} />
          <Stat label="Queue abandonment" value={`${k.abandonRate}%`} sub="left or no-show" tone={k.abandonRate > 12 ? 'warn' : 'default'} />
          <Stat label="Pre-order adoption" value={`${k.adoption}%`} sub="of guests who queued" />
          <Stat label="Order completion" value={`${k.completion} min`} sub="order → all dishes ready" />
          <Stat label="Revenue (incl. GST)" value={fmtMoney(k.revenue)} sub="net of refunds" />
          <Stat label="Order volume" value={k.orderCount} sub="paid orders" />
          <Stat label="Order accuracy" value={`${k.accuracy}%`} sub="no issue / no refund" tone={k.accuracy < 95 ? 'warn' : 'good'} />
        </div>

        <div className="grid gap-4 lg:grid-cols-2">
          <Chart title="Daily orders" note="Pre-orders and table (QR) orders">
            <BarChart data={a.daily}><CartesianGrid {...grid} /><XAxis dataKey="label" fontSize={10} interval={0} angle={-30} textAnchor="end" height={45} /><YAxis fontSize={11} allowDecimals={false} /><Tooltip /><Legend />
              <Bar dataKey="qr" name="Table orders" stackId="o" fill={C.green} /><Bar dataKey="preorders" name="Pre-orders" stackId="o" fill={C.blue} /></BarChart>
          </Chart>
          <Chart title="Revenue trend" note="₹ incl. GST, net of refunds">
            <LineChart data={a.daily}><CartesianGrid {...grid} /><XAxis dataKey="label" fontSize={10} interval={0} angle={-30} textAnchor="end" height={45} /><YAxis fontSize={11} tickFormatter={(v) => `₹${Math.round(v / 1000)}k`} /><Tooltip formatter={(v) => fmtMoney(v)} />
              <Line type="monotone" dataKey="revenue" name="Revenue" stroke={C.green} strokeWidth={2.5} dot={{ r: 3 }} /></LineChart>
          </Chart>
          <Chart title="Popular dishes" note="Portions ordered">
            <BarChart data={a.popular} layout="vertical" margin={{ left: 30 }}><CartesianGrid {...grid} /><XAxis type="number" fontSize={11} /><YAxis type="category" dataKey="name" width={120} fontSize={11} /><Tooltip />
              <Bar dataKey="qty" name="Portions" fill={C.green} radius={[0, 6, 6, 0]} /></BarChart>
          </Chart>
          <Chart title="Kitchen station workload" note="Total cooking minutes per station (actual where recorded, otherwise standard time)">
            <BarChart data={a.stationLoadData}><CartesianGrid {...grid} /><XAxis dataKey="station" fontSize={11} /><YAxis fontSize={11} /><Tooltip formatter={(v, n, p) => [`${v} min · ${p.payload.dishes} portions`, 'Cooking']} />
              <Bar dataKey="minutes" name="Cooking minutes" fill={C.orange} radius={[6, 6, 0, 0]} /></BarChart>
          </Chart>
          <Chart title="Average preparation time by dish" note="Actual average vs the standard time set in the menu">
            <BarChart data={a.prepByDish} layout="vertical" margin={{ left: 30 }}><CartesianGrid {...grid} /><XAxis type="number" fontSize={11} unit=" min" /><YAxis type="category" dataKey="name" width={120} fontSize={11} /><Tooltip /><Legend />
              <Bar dataKey="standard" name="Standard" fill={C.slate} /><Bar dataKey="actual" name="Actual" fill={C.orange} /></BarChart>
          </Chart>
          <Chart title="Peak restaurant hours" note="Arrivals and orders by hour of day">
            <ComposedChart data={a.hourly}><CartesianGrid {...grid} /><XAxis dataKey="label" fontSize={10} interval={0} angle={-30} textAnchor="end" height={45} /><YAxis fontSize={11} allowDecimals={false} /><Tooltip /><Legend />
              <Area type="monotone" dataKey="arrivals" name="Arrivals" fill="#bbf7d0" stroke={C.green} /><Line type="monotone" dataKey="orders" name="Orders" stroke={C.blue} strokeWidth={2} dot={false} /></ComposedChart>
          </Chart>
          <Chart title="Queue performance" note="Average wait (min) and abandonment rate (%) per day">
            <LineChart data={a.daily}><CartesianGrid {...grid} /><XAxis dataKey="label" fontSize={10} interval={0} angle={-30} textAnchor="end" height={45} /><YAxis fontSize={11} /><Tooltip /><Legend />
              <Line type="monotone" dataKey="avgWait" name="Avg wait (min)" stroke={C.blue} strokeWidth={2.5} /><Line type="monotone" dataKey="abandonRate" name="Abandoned (%)" stroke={C.orange} strokeWidth={2.5} /></LineChart>
          </Chart>
          <Chart title="Pre-order vs ordering after seating" note={`Average minutes from seating to first dish. Based on ${a.counts.preorders} pre-orders and ${a.counts.qrOrders} table orders. Avg order value: pre-order ${fmtMoney(a.comparison[1].preorder)}, table ${fmtMoney(a.comparison[1].qr)}.`}>
            <BarChart data={[{ name: 'Pre-order', min: a.comparison[0].preorder }, { name: 'Ordered after seating', min: a.comparison[0].qr }]}><CartesianGrid {...grid} /><XAxis dataKey="name" fontSize={11} /><YAxis fontSize={11} unit=" min" /><Tooltip />
              <Bar dataKey="min" name="Minutes to first dish" fill={C.blue} radius={[6, 6, 0, 0]} /></BarChart>
          </Chart>
        </div>
        <p className="text-xs text-slate-500">Waiting-time model: rule-based. Mean absolute error between the wait promised at joining and the wait that actually happened: <b>{k.predictionError} min</b> (seeded history, illustrative).</p>
      </div>
    </DashboardShell>
  )
}
